import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
const root = dirname(fileURLToPath(import.meta.url))
const result = await build({ absWorkingDir: root, entryPoints: ['client-entry.js'], bundle: true, external: ['react'], format: 'cjs', platform: 'browser', target: 'es2022', write: false })
const contents = `// Generated by build-client.js\nwindow.__ModuleLoader__.load({id:'independent-chief',factory:(require)=>{const module={exports:{}};\n${result.outputFiles[0].text}\nreturn Object.defineProperty({...module.exports},Symbol.toStringTag,{value:'Module'})}})\n`
const destination = join(root, 'client.js')
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== contents) throw new Error('client.js is stale')
} else await writeFile(destination, contents)
